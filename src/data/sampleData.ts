// Helper to build full week availability grid
export const buildFullAvailability = (
  days: string[],
  periods: number[],
  status: 'available' | 'unavailable' | 'unknown'
): Record<string, any> => {
  const grid: Record<string, any> = {};
  for (const day of days) {
    for (const p of periods) {
      grid[`${day}_${p}`] = status;
    }
  }
  return grid;
};

